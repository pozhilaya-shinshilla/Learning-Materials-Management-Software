"""Действия, привязанные к исходу транзакции: письма и операции с файлами.

Письмо нельзя отозвать, а файл на диске не откатывается вместе с БД. Поэтому всё, что выходит
за пределы базы, выполняется не посреди операции, а по её исходу:

- письмо и удаление файла — только после успешной фиксации (`on_commit`). Откат ничего не
  отправит и ничего не сотрёт, а соединение с БД к этому времени уже свободно: SMTP и его повторы
  не держат транзакцию открытой;
- копия загруженного файла — сразу, но с отменой на случай отката (`on_rollback`), чтобы не
  оставалось файлов-«сирот».

Сервисы зависят только от этого контракта и ничего не знают о БД. Настоящую реализацию даёт
`TransactionManager` (`src/database/transaction.py`).
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Callable

type Action = Callable[[], None]


class TransactionHooks(ABC):
    """Регистрация действий, которые зависят от исхода текущей транзакции."""

    @abstractmethod
    def on_commit(self, action: Action) -> None:
        """Выполнить `action` после успешной фиксации внешней транзакции.

        При откате действие отбрасывается. Ошибка действия не отменяет операцию: транзакция уже
        зафиксирована, поэтому ошибку записывают в лог, а не пробрасывают вызывающему коду.
        """

    @abstractmethod
    def on_rollback(self, action: Action) -> None:
        """Выполнить `action`, если транзакция откатится (в том числе при сбое самой фиксации).

        После успешной фиксации действие отбрасывается.
        """


class ImmediateHooks(TransactionHooks):
    """Когда транзакцией никто не управляет (юнит-тесты, вызывающий код сам ведёт сессию).

    `on_commit` выполняет действие сразу, `on_rollback` ничего не делает: откатывать нечему.
    """

    def on_commit(self, action: Action) -> None:
        """Выполнить действие немедленно."""
        action()

    def on_rollback(self, action: Action) -> None:
        """Отката здесь не бывает: действие отбрасывается."""
